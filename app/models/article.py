from sqlalchemy import Column, Integer, String, Text, DateTime, Float, JSON
from sqlalchemy.sql import func
from pgvector.sqlalchemy import Vector
from app.database import Base


class Article(Base):
    """Article model with vector embeddings for RAG retrieval"""

    __tablename__ = "articles"

    id = Column(Integer, primary_key=True, index=True)
    title = Column(Text, nullable=False)
    content = Column(Text, nullable=False)
    url = Column(String, unique=True, nullable=False, index=True)
    source = Column(String(255), nullable=False)  # e.g., "arXiv", "TechCrunch"
    source_type = Column(String(50), nullable=False, index=True)  # 'academic', 'industry', 'financial'
    published_date = Column(DateTime, nullable=False, index=True)
    scraped_at = Column(DateTime, server_default=func.now())

    # Vector embedding for semantic search (1536 dimensions for text-embedding-3-large)
    embedding = Column(Vector(1536))

    # Additional metadata stored as JSON
    article_metadata = Column(JSON, default={})

    # Summary fields (generated by AI)
    summary = Column(Text)
    key_points = Column(JSON)  # List of key points
    tags = Column(JSON)  # List of tags

    def __repr__(self):
        return f"<Article(id={self.id}, title='{self.title[:50]}...', source='{self.source}')>"

    def to_dict(self):
        """Convert article to dictionary for API responses"""
        return {
            "id": self.id,
            "title": self.title,
            "content": self.content,
            "url": self.url,
            "source": self.source,
            "sourceType": self.source_type,
            "publishedDate": self.published_date.isoformat() if self.published_date else None,
            "scrapedAt": self.scraped_at.isoformat() if self.scraped_at else None,
            "summary": self.summary,
            "keyPoints": self.key_points or [],
            "tags": self.tags or [],
            "metadata": self.article_metadata or {}
        }
